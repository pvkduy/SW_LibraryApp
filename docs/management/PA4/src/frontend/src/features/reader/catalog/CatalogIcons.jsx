/** Deterministic crisp SVG QR matrix generated from pickup code (for SuccessWithPickupQR) */
export function PickupQrSvg({ value = 'RSH-884021', size = 164 }) {
  const gridSize = 21
  let seed = 0
  for (let i = 0; i < value.length; i++) {
    seed = (seed * 31 + value.charCodeAt(i)) >>> 0
  }

  const isFinder = (r, c) =>
    (r < 7 && c < 7) || (r < 7 && c >= gridSize - 7) || (r >= gridSize - 7 && c < 7)

  const finderFilled = (r, c) => {
    const lr = r >= gridSize - 7 ? r - (gridSize - 7) : r
    const lc = c >= gridSize - 7 ? c - (gridSize - 7) : c
    if (lr === 0 || lr === 6 || lc === 0 || lc === 6) return true
    if (lr >= 2 && lr <= 4 && lc >= 2 && lc <= 4) return true
    return false
  }

  const cells = []
  for (let r = 0; r < gridSize; r++) {
    for (let c = 0; c < gridSize; c++) {
      let filled = false
      if (isFinder(r, c)) {
        filled = finderFilled(r, c)
      } else if (r === 6 || c === 6) {
        filled = (r + c) % 2 === 0
      } else {
        const h = ((r * 37 + c * 73) ^ seed) >>> 0
        filled = (h % 5 === 0 || h % 3 === 1)
      }
      if (filled) {
        cells.push(<rect key={`${r}-${c}`} x={c} y={r} width={1} height={1} fill="#18120e" />)
      }
    }
  }

  return (
    <svg width={size} height={size} viewBox={`-1 -1 ${gridSize + 2} ${gridSize + 2}`} role="img" aria-label={`Pickup QR ${value}`}>
      <rect x={-1} y={-1} width={gridSize + 2} height={gridSize + 2} fill="#ffffff" />
      {cells}
    </svg>
  )
}
